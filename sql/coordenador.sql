create table if not exists coordenador_execucoes (
  id           bigint generated by default as identity primary key,
  tipo         text not null,                       -- 'backoffice' (market_researcher_achados) | 'sintese' (sintese_mercado)
  status       text not null default 'EM_ANDAMENTO', -- 'EM_ANDAMENTO' | 'OK' | 'PARCIAL' | 'ERRO'
  iniciado_em  timestamptz not null default now(),
  concluido_em timestamptz,
  duracao_ms   integer,
  resumo       text,                                  -- ex.: "7 achado(s) atuais, 2 novo(s)"
  erro         text                                    -- texto do erro real, nunca stack trace completo/segredo
);

create index if not exists idx_coordenador_execucoes_tipo
  on coordenador_execucoes (tipo, iniciado_em desc);

-- RLS ativado e SEM policies: o backend Python usa a secret key (ignora
-- RLS); a leitura pela web usa a MESMA secret key no servidor (nunca no
-- navegador, ver web/lib/server/supabase.ts) - mesmo padrão de todas as
-- outras tabelas do projeto (sql/schema.sql, sql/market_researcher_achados.sql).
alter table coordenador_execucoes enable row level security;
