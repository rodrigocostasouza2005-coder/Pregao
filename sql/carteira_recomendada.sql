-- Três tabelas NOVAS, sem nenhuma relação com posicoes_carteira (posição
-- REAL do Rodrigo, data/posicoes.py) nem com as tabelas do Radar de
-- Quedas (carteiras públicas de terceiros, data/radar_quedas.py) -
-- conceitos deliberadamente separados (ver docstring de
-- data/carteira_recomendada.py).
--
-- carteira_recomendada_itens: snapshot VIGENTE da carteira (1 linha por
-- ticker, substituída por upsert a cada rodada - data/
-- carteira_recomendada.py:salvar_carteira). Nunca um DELETE em massa:
-- cada ticker é upsert pelo próprio ticker.
-- carteira_recomendada_historico: log append-only de toda alteração
-- (peso, tese, saída do ativo, etc.) - nunca editado/apagado por quem
-- consome, só inserido (data/carteira_recomendada.py:registrar_revisao).
-- carteira_recomendada_acompanhamento: 1 linha por ativo por data de
-- checagem - recomendado (peso/preço na recomendação) vs. efetivo (preço
-- na data da checagem), pra comparar desempenho esperado x realizado ao
-- longo do tempo (data/carteira_recomendada.py:registrar_acompanhamento).
--
-- Idempotente (if not exists em tudo, seguro re-rodar).

create table if not exists carteira_recomendada_itens (
  ticker              text primary key,
  setor               text,
  peso_pct            numeric,
  justificativa       text,
  preco_referencia    numeric,
  preco_alvo          numeric,
  tese                text,
  riscos              jsonb,                      -- lista de strings (critérios "contrários" do Comitê)
  criterio_saida      text,
  data_revisao        date,
  origem_analise_id   text,                        -- referencia coordenador_analises.id, SEM FK formal (mesmo motivo do resto do projeto - ciclos de vida independentes)
  atualizado_em       timestamptz not null default now()
);

create table if not exists carteira_recomendada_historico (
  id               bigint generated by default as identity primary key,
  ticker           text not null,
  campo            text not null,                 -- 'peso_pct' / 'tese' / 'saida_da_carteira' / ...
  valor_anterior   jsonb,
  valor_novo       jsonb,
  motivo           text,
  registrado_em    timestamptz not null default now()
);

create index if not exists idx_carteira_recomendada_historico_ticker on carteira_recomendada_historico (ticker);
create index if not exists idx_carteira_recomendada_historico_registrado_em on carteira_recomendada_historico (registrado_em desc);

create table if not exists carteira_recomendada_acompanhamento (
  id                      bigint generated by default as identity primary key,
  ticker                  text not null,
  data_referencia         date not null,
  peso_recomendado_pct    numeric,
  preco_referencia        numeric,                  -- preço no momento da recomendação
  preco_atual             numeric,                   -- preço na data_referencia desta checagem
  retorno_pct             numeric,
  registrado_em           timestamptz not null default now(),
  unique (ticker, data_referencia)
);

create index if not exists idx_carteira_recomendada_acompanhamento_ticker on carteira_recomendada_acompanhamento (ticker);
create index if not exists idx_carteira_recomendada_acompanhamento_data on carteira_recomendada_acompanhamento (data_referencia desc);

-- RLS ativado e SEM policies: mesmo padrão de todas as outras tabelas do
-- projeto (só a service role key do backend Python lê/escreve).
alter table carteira_recomendada_itens enable row level security;
alter table carteira_recomendada_historico enable row level security;
alter table carteira_recomendada_acompanhamento enable row level security;

