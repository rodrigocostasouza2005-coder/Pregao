-- PREGÃO — persistência do COORDENADOR CENTRAL (Fase E, pedido do
-- Rodrigo, 2026-10-31). Duas tabelas NOVAS - NÃO reaproveita
-- coordenador_execucoes (sql/coordenador.sql): aquela é o log do
-- SCHEDULER puro (jobs/coordenador.py, roda via GitHub Actions), formato
-- incompatível (sem id de análise, sem granularidade por especialista).
--
-- coordenador_analises: 1 linha por chamada de um fluxo (ver
-- data/coordenador_central/fluxos.py) - gravada EM_ANDAMENTO antes de
-- rodar qualquer especialista, atualizada no final (CONCLUIDA/ERRO).
-- coordenador_especialistas_execucoes: 1 linha por especialista
-- acionado dentro de uma análise - usada pra monitorar desempenho
-- (taxa de sucesso/tempo médio por especialista ao longo do tempo, ver
-- data/coordenador_central/persistencia.py:metricas_especialistas).
--
-- Rode isso uma vez em: Supabase > SQL Editor > New query. Idempotente
-- (if not exists em tudo, seguro re-rodar).

create table if not exists coordenador_analises (
  id            text primary key,                        -- uuid4().hex, gerado em Python (persistencia.py:iniciar_analise)
  solicitacao   text not null,                            -- ex: "Analisar PETR4"
  tipo_fluxo    text not null,                            -- analise_ticker / comparar_casas / catalisadores
  ticker        text,
  status        text not null default 'EM_ANDAMENTO',     -- EM_ANDAMENTO / CONCLUIDA / ERRO
  iniciado_em   timestamptz not null default now(),
  concluido_em  timestamptz,
  duracao_ms    int,
  resultado     jsonb,                                    -- dict consolidado inteiro (nunca texto completo de relatório dentro)
  erro          text
);

create index if not exists idx_coordenador_analises_status on coordenador_analises (status);
create index if not exists idx_coordenador_analises_ticker on coordenador_analises (ticker);
create index if not exists idx_coordenador_analises_iniciado_em on coordenador_analises (iniciado_em desc);

create table if not exists coordenador_especialistas_execucoes (
  id               bigint generated by default as identity primary key,
  analise_id       text not null,   -- referencia coordenador_analises.id, SEM FK formal (mesmo motivo das outras tabelas do projeto - ciclos de vida independentes, ver sql/research_premissas.sql)
  especialista_id  text not null,
  disponivel       boolean not null,
  duracao_ms       int,
  erro             text,            -- erro_tecnico do executor, só pra diagnóstico - nunca exibido na UI
  executado_em     timestamptz not null default now()
);

create index if not exists idx_coord_especialistas_execucoes_especialista on coordenador_especialistas_execucoes (especialista_id);
create index if not exists idx_coord_especialistas_execucoes_analise on coordenador_especialistas_execucoes (analise_id);

-- RLS ativado e SEM policies: mesmo padrao de todas as outras tabelas
-- do projeto (so' a service role key do backend Python le/escreve).
alter table coordenador_analises enable row level security;
alter table coordenador_especialistas_execucoes enable row level security;
