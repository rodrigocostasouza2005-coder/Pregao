-- PREGAO — biblioteca PERMANENTE de premissas/projecoes extraidas de
-- relatorios de Research (Equity Research Library, pedido do Rodrigo
-- 2026-10-30). Diferente de research_itens (sql/research.sql), que e'
-- perecivel (apagado em 5 dias, ver data/research/store.py:
-- apagar_itens_antigos) - esta tabela NUNCA e' limpa: guarda so' a
-- ESTRUTURA extraida por IA do relatorio (tipo de documento, premissas
-- da tese, projecoes de receita/EBITDA/lucro quando explicitas no
-- texto) + metadado minimo (casa/titulo/tickers/data) pra o documento
-- continuar identificavel mesmo depois que a linha original de
-- research_itens tiver sido apagada. O texto completo do relatorio
-- NUNCA e' persistido aqui nem em research_itens (mesmo principio,
-- respeito a paywall/direitos de autor - ver data/research/resumir.py).
-- Rode isso uma vez em: Supabase > SQL Editor > New query. Idempotente
-- (if not exists em tudo, seguro re-rodar).

create table if not exists research_premissas (
  id               bigint generated by default as identity primary key,
  link             text not null unique,      -- mesmo link de research_itens (sem FK: research_itens e perecivel, esta tabela nao)
  casa             text not null,
  titulo           text not null,
  tickers          text[] not null default '{}',
  data_publicacao  text,                       -- copia de research_itens.data (YYYY-MM-DD), preservada antes do item perecer
  tipo_documento   text,                       -- classificacao fina (INICIACAO_COBERTURA / ATUALIZACAO_COBERTURA / ATUALIZACAO_RESULTADOS / RELATORIO_SETORIAL / ESTRATEGIA_INVESTIMENTOS / CARTEIRA_RECOMENDADA / REVISAO_PRECO_ALVO / MUDANCA_RECOMENDACAO / VALUATION / COMENTARIO_RESULTADO_TRIMESTRAL), nullable - so' quando o modelo identifica com confianca
  premissas        text[] not null default '{}',   -- hipoteses centrais da tese, 1 frase cada - extraidas do texto, nunca inventadas
  projecoes        jsonb not null default '{}',     -- so' chaves (receita/ebitda_margem/lucro) que o documento de fato mencionou
  recomendacao     text,
  preco_alvo       numeric,
  modelo_extracao  text,
  extraido_em      timestamptz not null default now()
);

create index if not exists idx_research_premissas_casa on research_premissas (casa);
create index if not exists idx_research_premissas_tickers on research_premissas using gin (tickers);

-- RLS ativado e SEM policies: mesmo padrao de todas as outras tabelas
-- do projeto (so' a service role key do backend Python le/escreve).
alter table research_premissas enable row level security;
