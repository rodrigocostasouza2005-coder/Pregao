-- PREGAO — telemetria das chamadas de IA da ARQUITETURA HIBRIDA (missao
-- "PREGÃO 2.1 — IA real híbrida", 2026-11-13). PROPOSTO, NAO APLICADO em
-- producao por este agente (regra da missao: nenhuma alteracao de schema
-- e' rodada automaticamente) - rode isso em: Supabase > SQL Editor > New
-- query, quando aprovado.
--
-- Por que uma tabela NOVA e nao so' estender resumos_ia_cache (ver
-- sql/ia_cache.sql): a cache de IA deliberadamente APAGA a reserva
-- ('gerando') quando a geracao falha (ver data/ia_cache.py:
-- _liberar_reserva) - isso e' correto pro proposito dela (nao bloquear
-- a proxima tentativa pra sempre), mas significa que uma FALHA de IA
-- nunca fica registrada em lugar nenhum consultavel - exatamente o
-- oposto do que a missao pede ("registrar... falha, se houver, de um
-- jeito consultavel depois"). Esta tabela e' so' AUDITORIA/OBSERVABILIDADE
-- (nunca usada por nenhuma logica de cache/retry) - toda chamada de IA
-- da camada hibrida grava 1 linha aqui, sucesso OU falha, sem nunca
-- apagar nada.
--
-- Migracao idempotente (IF NOT EXISTS em tudo) - rodar de novo nao apaga
-- nem altera nenhuma linha ja existente.

create table if not exists ia_hibrida_execucoes (
  id              bigint generated by default as identity primary key,
  origem          text not null,       -- 'market_researcher_sintese_research' | 'coordenador_sintese_divergencia' (novas origens futuras so' adicionam valor novo aqui, nunca exigem migracao)
  ticker          text,
  provedor        text not null,       -- 'groq' (unico provedor de IA generativa usado nesta camada; embeddings do Gemini tem telemetria propria, ver data/research/embeddings.py)
  modelo          text,                -- modelo realmente usado nesta chamada (principal OU fallback - nunca o nome do principal quando o fallback respondeu)
  entrada_hash    text not null,       -- sha256 do payload enviado a IA (identidade da entrada, nunca o prompt gigante em texto puro)
  entrada_resumo  text,                -- descricao curta e legivel da entrada (ex: "3 casas: Genial Analisa, XP Investimentos, BTG Pactual")
  fontes          jsonb,               -- lista das fontes reais usadas (casa/link/data_publicacao, ou especialista_id/recomendacao) - nunca um resumo vago
  duracao_ms      int,                 -- duracao da chamada de IA (principal + fallback se houve), nao do fluxo inteiro
  sucesso         boolean not null,
  motivo_falha    text,                -- NULL quando sucesso=true
  resultado_resumo text,               -- preview curto do texto gerado (nunca o payload de entrada nem o prompt completo)
  criado_em       timestamptz not null default now()
);

create index if not exists idx_ia_hibrida_execucoes_origem on ia_hibrida_execucoes (origem);
create index if not exists idx_ia_hibrida_execucoes_ticker on ia_hibrida_execucoes (ticker);
create index if not exists idx_ia_hibrida_execucoes_criado_em on ia_hibrida_execucoes (criado_em desc);
create index if not exists idx_ia_hibrida_execucoes_sucesso on ia_hibrida_execucoes (sucesso);

-- RLS ativado e SEM policies: mesmo padrao de todas as outras tabelas do
-- projeto (so' a service role key do backend Python le/escreve).
alter table ia_hibrida_execucoes enable row level security;
