-- NÃO estende research_itens: aquela tabela é o contrato de RELATÓRIO
-- de casa de research (preco_alvo/recomendacao extraídos do PRÓPRIO
-- documento, chave = link do relatório). Um post do X é outra coisa -
-- sinal social, não documento oficial, com ciclo de vida de verificação
-- próprio (detectado -> confirmado/refutado/expirado) e níveis de
-- evidência que NUNCA existem em research_itens. O contrato já estava
-- desenhado em data/x_signals.py (FASE 4 da auditoria 2026-10-09,
-- dataclass Sinal) - esta tabela só persiste esse mesmo contrato, sem
-- redesenhar nada.
--
-- Conector permanece DESLIGADO (data/x_signals.py:DISPONIVEL=False) até
-- credencial paga ser aprovada - ver MOTIVO_INDISPONIVEL. Esta tabela
-- fica pronta e vazia até então; reprocessamento preserva histórico via
-- versao_classificador (nunca sobrescreve uma classificação antiga sem
-- registrar a versão nova).

create table if not exists x_sinais (
  id                     bigint generated by default as identity primary key,
  post_id                text not null,              -- ID do post no X - chave de dedup (upsert)
  link_original          text not null,
  autor                  text not null,               -- @handle, sempre preservado
  autor_tipo             text,                        -- institucional / funcionario_casa / analista_independente / pessoa_fisica / desconhecido
  conta_verificada       boolean not null default false, -- informativo - NUNCA usado por si so para subir nivel_evidencia
  texto                  text,                        -- texto do post - sujeito a retencao (ver limpar_textos_expirados)
  horario_publicacao     timestamptz,
  horario_captura        timestamptz not null default now(),

  ticker                 text,
  empresa                text,
  setor                  text,
  tema                   text,
  categoria              text not null,               -- fato_confirmado/opiniao_analista/tese_investimento/estimativa_projecao/rumor_nao_confirmado/noticia/comentario_macro/sem_relevancia
  tipo_conteudo          text,

  relevancia             smallint,                    -- 0-100, calculada - nunca inventada se nao houver base
  relevancia_motivo      text,                         -- explicacao textual OBRIGATORIA se relevancia preenchida
  credibilidade          smallint,                     -- 0-100, NULL se nao houver historico suficiente do autor (nunca 0 "por omissao")
  credibilidade_motivo   text,

  sentimento             text,                         -- positivo/negativo/neutro/misto
  argumento_central      text,
  catalisador            text,
  risco                  text,
  necessita_investigacao boolean not null default false,

  nivel_evidencia        text not null default 'nivel_1_sinal_social',
  estado                 text not null default 'detectado',
  chave_acontecimento     text,                        -- dedup por FATO (varios posts, mesmo acontecimento)
  mesma_origem           boolean not null default false,
  evidencias_confirmacao jsonb not null default '[]',  -- fontes PRIMARIAS que confirmam (obrigatorio se nivel=confirmado)
  fontes_cruzadas        jsonb not null default '[]',  -- resultado de cobertura_cruzada_casas/obter_noticias (contexto, nao confirmacao)

  versao_classificador   text not null,                -- permite reprocessar quando o classificador melhorar
  classificado_em        timestamptz not null default now(),
  criado_em              timestamptz not null default now(),
  atualizado_em          timestamptz not null default now()
);

create unique index if not exists idx_x_sinais_post_id on x_sinais (post_id);
create index if not exists idx_x_sinais_ticker on x_sinais (ticker);
create index if not exists idx_x_sinais_chave_acontecimento on x_sinais (chave_acontecimento);
create index if not exists idx_x_sinais_captura on x_sinais (horario_captura desc);
create index if not exists idx_x_sinais_estado on x_sinais (estado);

-- RLS ativado e SEM policies: o backend Python usa a secret key, que
-- sempre ignora RLS - mesmo padrao de todas as outras tabelas do
-- projeto (sql/schema.sql, sql/research.sql, sql/coordenador.sql).
alter table x_sinais enable row level security;

-- Controle de consumo/limites da API (rate limit) - 1 linha por janela
-- de consulta, nunca cresce sem limite (upsert por `janela`).
create table if not exists x_radar_consumo (
  janela        text primary key,                     -- ex: '2026-10-30T15:00' (bucket de 15min, igual ao rate-limit window do X)
  leituras      integer not null default 0,
  limite        integer,                               -- limite conhecido da credencial atual, quando a API informa (header x-rate-limit-limit)
  atualizado_em timestamptz not null default now()
);

alter table x_radar_consumo enable row level security;

-- Historico de classificacao: ANTES de sobrescrever a classificacao
-- atual de um post (reprocessamento com versao_classificador nova),
-- a linha atual de x_sinais e' copiada pra aqui - preserva o que o
-- classificador achou da ULTIMA vez, pedido explicito da secao 9
-- ("permitir reprocessar... preservando o historico de classificacao").
create table if not exists x_sinais_historico (
  id                   bigint generated by default as identity primary key,
  post_id              text not null,
  categoria            text,
  relevancia           smallint,
  relevancia_motivo    text,
  credibilidade        smallint,
  credibilidade_motivo text,
  nivel_evidencia      text,
  estado               text,
  versao_classificador text not null,
  classificado_em      timestamptz not null,
  substituido_em        timestamptz not null default now()
);

create index if not exists idx_x_sinais_historico_post on x_sinais_historico (post_id, substituido_em desc);

alter table x_sinais_historico enable row level security;
