create table if not exists research_recomendacoes_historico (
  id            bigint generated by default as identity primary key,
  casa          text not null,                       -- ex: 'Genial Analisa' (mesmo nome usado em research_itens.casa)
  ticker        text not null,
  recomendacao  text,                                -- como a casa publica (COMPRA/NEUTRO/VENDA etc.) - nunca normalizada/inventada aqui
  preco_alvo    numeric,                             -- nullable: a casa pode mudar a recomendacao sem publicar preco-alvo
  potencial_pct numeric,                             -- potencial publicado pela propria casa, quando ha' (nao recalculado aqui)
  capturado_em  timestamptz not null default now()   -- quando ESTE snapshot foi gravado
);

-- Consulta dominante: ultimo(s) snapshot(s) de um casa+ticker, mais
-- recente primeiro (historico.py:ultimo_snapshot/historico_ticker/
-- _ultimo_snapshot_por_ticker/_ultimos_dois_por_ticker). Mesmo nome do
-- indice proposto em sql/research.sql - os dois arquivos convergem.
create index if not exists idx_research_hist_casa_ticker
  on research_recomendacoes_historico (casa, ticker, capturado_em desc);

-- Indice adicional desta revisao (2026-11-26): historico.py:
-- _tickers_capturados_hoje filtra por casa + capturado_em >= inicio do
-- dia SEM ticker no predicado - o indice acima so' serve por prefixo
