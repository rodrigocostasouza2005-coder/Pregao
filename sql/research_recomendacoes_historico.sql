-- cobre esse acesso direto. Custo: 1 indice a mais numa tabela que
-- cresce devagar (poucas linhas por ticker/ano).
create index if not exists idx_research_hist_casa_capturado
  on research_recomendacoes_historico (casa, capturado_em desc);

