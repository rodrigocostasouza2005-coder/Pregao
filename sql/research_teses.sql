-- PREGAO — histórico de teses de investimento por usuário+ticker
-- (Research Intelligence / integração Market Researcher, 2026-10-22).
-- Rode isso uma vez em: Supabase > SQL Editor > New query. Idempotente
-- (if not exists em tudo, seguro re-rodar).
--
-- Adaptação do skill "thesis-tracker" do Market Researcher oficial da
-- Anthropic (plugins/vertical-plugins/equity-research/skills/thesis-tracker)
-- pro Supabase já usado pelo projeto: cada chamada de
-- data/research/tese.py:registrar_versao grava uma linha NOVA (nunca
-- UPDATE) - é um log append-only, igual research_recomendacoes_historico
-- (ver sql/research.sql) - "track disconfirming evidence as rigorously
-- as confirming evidence" só funciona se nada for sobrescrito.
--
-- Escopo por usuário (usuario_sub, chave do Google login via st.user.sub)
-- porque uma tese é uma leitura pessoal de quem a escreveu, não um fato
-- editorial compartilhado como research_itens.

create table if not exists research_teses (
  id             bigint generated by default as identity primary key,
  usuario_sub    text not null,
  ticker         text not null,
  posicao        text,                      -- 'LONG' / 'SHORT', nullable (nem toda tese precisa declarar)
  tese           text not null,              -- 1-2 frases, a tese central
  premissas      text[] not null default '{}',
  riscos         text[] not null default '{}',
  catalisadores  text[] not null default '{}',
  conviccao      text,                       -- 'ALTA' / 'MEDIA' / 'BAIXA'
  preco_alvo_tese numeric,                   -- hipótese do PRÓPRIO analista (HIPOTESE_ANALISTA) - nunca confundir com preco_alvo de research_itens (ESTIMATIVA_TERCEIRO, vem da casa de research)
  registrado_em  timestamptz not null default now()
);

create index if not exists idx_research_teses_usuario_ticker
  on research_teses (usuario_sub, ticker, registrado_em desc);

-- RLS ativado e SEM policies: o backend Python usa a secret key, que
-- sempre ignora RLS. Mesmo padrão de todas as outras tabelas do projeto
-- (ver sql/schema.sql, sql/research.sql).
alter table research_teses enable row level security;
