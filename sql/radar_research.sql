-- PREGÃO — Radar de carteiras recomendadas e alertas de queda.
-- Migration idempotente. Executar no Supabase SQL Editor.
create table if not exists radar_carteiras_recomendadas (
  id bigint generated by default as identity primary key,
  casa text not null,
  carteira text not null,
  ticker text not null,
  empresa text,
  recomendacao text,
  preco_alvo numeric,
  data_publicacao date,
  validade_ate date,
  fonte_url text not null,
  verificado_em timestamptz not null default now(),
  status_coleta text not null default 'NAO_VERIFICADO',
  vigente boolean not null default true,
  unique (casa, ticker, carteira)
);
create index if not exists idx_radar_carteiras_ticker_vigente
  on radar_carteiras_recomendadas (ticker, vigente);
alter table radar_carteiras_recomendadas enable row level security;

create table if not exists radar_alertas_queda (
  id bigint generated by default as identity primary key,
  ticker text not null,
  empresa text,
  pregao date not null,
  preco_atual numeric not null,
  fechamento_anterior numeric not null,
  variacao_pct numeric not null,
  cotacao_em timestamptz not null,
  tipo_cotacao text not null,
  casas text[] not null default '{}',
  carteiras text[] not null default '{}',
  fontes text[] not null default '{}',
  alertado_em timestamptz not null default now(),
  status text not null default 'PENDENTE_ENVIO',
  email_enviado_em timestamptz,
  erro_envio text,
  unique (ticker, pregao)
);
create index if not exists idx_radar_alertas_data
  on radar_alertas_queda (alertado_em desc);
alter table radar_alertas_queda enable row level security;

-- Registro independente das execuções e entregas do Morning Call.
create table if not exists morning_call_execucoes (
  id bigint generated by default as identity primary key,
  executado_em timestamptz not null default now(),
  status text not null,
  destinatario text,
  erro text,
  conteudo text
);
create index if not exists idx_morning_call_execucoes_em
  on morning_call_execucoes (executado_em desc);
alter table morning_call_execucoes enable row level security;

