-- Upsert por `chave` (coletor|categoria|tipo, determinística) - NÃO é
-- append-only como research_teses/research_recomendacoes_historico:
-- um achado que continua acontecendo deve ATUALIZAR a mesma linha
-- (ultima_ocorrencia_em, ocorrencias++), nunca acumular 1 linha nova
-- por checagem. Ver data/market_researcher.py:registrar_achados_atuais.

create table if not exists market_researcher_achados (
  id                     bigint generated by default as identity primary key,
  chave                  text not null unique,
  coletor                text not null,
  categoria              text not null,
  tipo                   text not null,            -- mesmo codigo_estado de data/saude_dados.py (ex: FALHA_EXECUCAO)
  descricao              text,
  severidade             text not null,             -- 'CRITICO' / 'ATENCAO'
  status                 text not null default 'ABERTO',  -- 'ABERTO' / 'RESOLVIDO'
  primeira_ocorrencia_em timestamptz not null default now(),
  ultima_ocorrencia_em   timestamptz not null default now(),
  ocorrencias            integer not null default 1,
  causa_raiz             text,                      -- preenchido manualmente quando a causa for confirmada
  commit_correcao        text,                       -- ex: SHA do commit que corrigiu
  resolvido_em           timestamptz
);

create index if not exists idx_market_researcher_achados_status
  on market_researcher_achados (status, ultima_ocorrencia_em desc);

-- RLS ativado e SEM policies: o backend Python usa a secret key, que
-- sempre ignora RLS. Mesmo padrão de todas as outras tabelas do projeto
-- (ver sql/schema.sql, sql/research.sql, sql/research_teses.sql).
alter table market_researcher_achados enable row level security;
