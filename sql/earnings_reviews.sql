-- PREGAO — Earnings Reviewer (Modulo 2): historico versionado das notas
-- de resultado trimestral. Rode isso uma vez em: Supabase > SQL Editor > New query

-- Append-only de proposito (ver data/earnings/reviewer.py:salvar_versao -
-- so' INSERT, nunca UPDATE/DELETE): cada analise de um ticker/periodo e'
-- uma linha NOVA, nunca sobrescreve a nota de uma analise anterior do
-- mesmo periodo (ex: reprocessamento depois de uma re-apresentacao da
-- CVM) - quem le' historico decide qual versao usar, a tabela preserva
-- todas. `conteudo` guarda a nota estruturada inteira (jsonb) - mesmo
-- padrao de morning_call_execucoes.conteudo (texto completo persistido,
-- nao so' um resumo).
create table if not exists earnings_reviews (
  id            bigint generated by default as identity primary key,
  ticker        text not null,
  pais          text not null,              -- 'BR' ou 'US'
  periodo_label text not null,              -- ex: '2T2026' (BR) ou '2026-04-01 a 2026-06-27' (US)
  gerado_em     timestamptz not null default now(),
  conteudo      jsonb not null              -- nota completa (metricas, interpretacoes, limitacoes, fontes)
);

create index if not exists idx_earnings_reviews_ticker
  on earnings_reviews (ticker, pais, gerado_em desc);

-- RLS ativado e SEM policies: o backend Python usa a secret key, que
-- sempre ignora RLS. Mesmo padrao das demais tabelas (ver sql/research.sql).
alter table earnings_reviews enable row level security;
