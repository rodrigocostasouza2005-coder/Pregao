-- Contexto (achado real da auditoria, ver data/research/store.py:
-- salvar_itens): hoje o upsert por link (on_conflict="link") SOBRESCREVE
-- a linha anterior de research_itens sem deixar nenhum rastro - se a
-- fonte republicar o MESMO link com titulo/data diferentes (relatorio
-- corrigido/atualizado), a versao anterior simplesmente desaparece, sem
-- registro de que uma mudanca aconteceu. research_recomendacoes_historico
-- (sql/research.sql) já resolve esse problema pro CAMPO ESTRUTURADO
-- recomendacao/preco-alvo (ver data/research/historico.py) - esta tabela
-- resolve o equivalente pro ITEM inteiro (titulo/data/resumo/tickers).
--
-- data/research/store.py:_versionar_antes_do_upsert ja' esta' pronto pra
-- escrever aqui (melhor esforco - se esta tabela nao existir ainda, so'
-- loga e segue, nunca bloqueia o upsert principal) assim que esta
-- migracao for aplicada: so' grava uma linha quando titulo OU data
-- mudam de verdade pro mesmo link (nunca a cada recoleta de rotina, que
-- tipicamente repete o mesmo titulo/data) - cresce devagar, so' quando
-- uma versao de verdade muda.
--
-- Diferente de research_itens (perecivel, retencao de 5 dias - ver
-- store.RETENCAO_DIAS/apagar_itens_antigos), este historico NAO e'
-- apagado automaticamente - e' justamente o rastro que research_itens,
-- por design, nao guarda.

create table if not exists research_itens_historico (
  id             bigint generated by default as identity primary key,
  link           text not null,              -- mesmo link da linha original (nao e' PK aqui - 1 link pode ter varias versoes)
  casa           text,
  titulo         text,
  data           text,
  autor          text,
  tipo           text,
  tickers        text[] default '{}',
  resumo         text,                       -- resumo por IA que a versao ANTERIOR tinha, se algum (nunca o texto completo original)
  modelo_resumo  text,
  preco_alvo     numeric,
  recomendacao   text,
  coletado_em    timestamptz,                -- coletado_em da versao ANTERIOR (quando ela foi salva originalmente)
  substituido_em timestamptz not null default now()  -- quando esta versao foi arquivada (upsert da versao NOVA aconteceu agora)
);

create index if not exists idx_research_itens_historico_link
  on research_itens_historico (link, substituido_em desc);

